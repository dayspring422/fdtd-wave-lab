// Numerical validation of the FDTD solver. Runs without a browser:
//
//   node tests/validate.js           full run (about a minute)
//   node tests/validate.js --quick   coarser grids only
//
// It checks three things and writes the results to VALIDATION.md:
//   1. Wave speed in vacuum and glass, measured from the field, against theory.
//   2. Refraction: the transmitted angle measured from the field, against Snell's law.
//   3. The absorbing boundary: how much a wave reflects off it, graded loss vs PML.
// Parts 1 and 2 are repeated at several grid resolutions to show the error shrinking.

require('../js/solver.js');
require('../js/measure.js');
const fs = require('fs');
const path = require('path');
const WL = globalThis.WaveLab;

const quick = process.argv.includes('--quick');
const RESOLUTIONS = quick ? [8, 12, 16] : [8, 12, 16, 24];   // cells per vacuum wavelength
const N_GLASS = 1.5;
const THETA = 25;   // incidence angle set at the source, degrees
const deg = r => r * 180 / Math.PI, rad = d => d * Math.PI / 180;
const out = [];
const log = (s = '') => { console.log(s); out.push(s); };
const pct = x => (x * 100).toFixed(3) + '%';

// Order of convergence between successive resolutions: error ~ (1/lambda)^p.
function orders(lams, errs) {
  return errs.map((e, i) => (i === 0 ? '' : (Math.log(errs[i - 1] / e) / Math.log(lams[i] / lams[i - 1])).toFixed(2)));
}

// Yee-grid dispersion relation for TMz:
//   [sin(w dt/2) / (c' dt)]^2 = [sin(kx dx/2)/dx]^2 + [sin(ky dx/2)/dx]^2,  c' = c/n
// In grid units (dx = 1, c dt = S) this gives kx for a given ky.
function yeeKx(lam, n, ky, S = 0.5) {
  const w = 2 * Math.PI * S / lam;
  const rhs = (n * Math.sin(w / 2) / S) ** 2 - Math.sin(ky / 2) ** 2;
  return 2 * Math.asin(Math.sqrt(rhs));
}

function runToSteadyState(sim, settle) {
  const lock = WL.createLockIn(sim, { settle });
  while (!lock.ready) { sim.step(); lock.sample(); }
  return lock;
}

// ---------------------------------------------------------------- 1. wave speed
log('# Validation results');
log();
log(`Generated by \`node tests/validate.js${quick ? ' --quick' : ''}\`. Courant number S = 0.5, glass n = ${N_GLASS}.`);
log();
log('## 1. Phase velocity');
log();
log('A plane wave travels along x. Its phase velocity is measured from the field as v = ω/k, where k comes from the phase difference between neighbouring cells. "Yee theory" is the speed the discrete scheme should produce according to its dispersion relation; "error" is the difference from the exact continuum value (c in vacuum, c/n in glass).');
log();
log('| cells per λ | medium | measured v/c | Yee theory v/c | exact v/c | error vs exact | order |');
log('|---|---|---|---|---|---|---|');

const speedRows = { vacuum: [], glass: [] };
for (const lam of RESOLUTIONS) {
  const W = 30 * lam, H = 4 * lam;
  for (const medium of ['vacuum', 'glass']) {
    const sim = WL.createSolver({ W, H });
    sim.lambda = lam; sim.n = N_GLASS;
    sim.sources = [{ type: 'line', u: lam }];
    if (medium === 'glass') for (let v = 0; v < H; v++) for (let u = 0; u < W; u++) sim.mat[sim.K(u, v)] = WL.GLASS;
    sim.dirty = true;
    const lock = runToSteadyState(sim, 70 * lam);
    const kv = WL.waveVector(sim, lock, (u, v) => u >= 5 * lam && u <= 22 * lam && v >= lam && v < 3 * lam);
    const n = medium === 'glass' ? N_GLASS : 1;
    const measured = WL.speedOf(sim, kv);
    const yee = (2 * Math.PI / lam) / yeeKx(lam, n, 0);
    const exact = 1 / n;
    speedRows[medium].push({ lam, measured, yee, exact, err: Math.abs(measured - exact) / exact });
  }
}
for (const medium of ['vacuum', 'glass']) {
  const rows = speedRows[medium];
  const ord = orders(rows.map(r => r.lam), rows.map(r => r.err));
  rows.forEach((r, i) => log(`| ${r.lam} | ${medium} | ${r.measured.toFixed(5)} | ${r.yee.toFixed(5)} | ${r.exact.toFixed(5)} | ${pct(r.err)} | ${ord[i]} |`));
}
log();
log('The measured speed matches the Yee prediction closely at every resolution, which checks the implementation. The error against the exact speed falls roughly as 1/λ², the expected second-order convergence of the Yee scheme. Glass is harder to resolve because the wavelength inside it is shorter by a factor of n.');

// ---------------------------------------------------------------- 2. refraction
log();
log('## 2. Refraction angle');
log();
log(`A wide Gaussian beam (half-width 5λ) hits a vacuum/glass interface at about ${THETA}°. Everything is read from the field, in regions away from the source and clear of the reflected beam. Snell's law is conservation of the wavenumber along the interface, kᵧ, so the incident angle is taken from the measured kᵧ of the incoming beam (sin θ₁ = kᵧ/k₀). The transmitted angle θ₂ is the measured direction of the wave inside the glass. It is compared with Snell's law, and with the angle the Yee dispersion relation predicts for the same kᵧ. The geometry scales with the wavelength, so every run is the same physical experiment at a different resolution.`);
log();
log('| cells per λ | θ₁ from measured kᵧ | θ₂ measured | θ₂ Snell | error vs Snell | θ₂ Yee theory | error vs Yee | order |');
log('|---|---|---|---|---|---|---|---|');

const refr = [];
for (const lam of RESOLUTIONS) {
  const W = 40 * lam, H = 26 * lam;
  const sim = WL.createSolver({ W, H });
  sim.lambda = lam; sim.n = N_GLASS;
  const uI = 20 * lam, vHit = 11 * lam, srcU = lam;
  sim.sources = [{ type: 'line', u: srcU, angle: THETA, width: 5 * lam, vc: vHit - (uI - srcU) * Math.tan(rad(THETA)) }];
  for (let v = 0; v < H; v++) for (let u = uI; u < W; u++) sim.mat[sim.K(u, v)] = WL.GLASS;
  sim.dirty = true;
  const t0 = Date.now();
  const lock = runToSteadyState(sim, 90 * lam);
  const e = 2 * lam;
  const inc = WL.strongCells(sim, lock, (u, v) => u >= 4 * lam && u <= 11 * lam && v > e && v < H - e, 0.6);
  const tra = WL.strongCells(sim, lock, (u, v) => u >= uI + 3 * lam && u <= uI + 15 * lam && v > e && v < H - e, 0.6);
  const k1 = WL.waveVector(sim, lock, inc), k2 = WL.waveVector(sim, lock, tra);
  // Snell's law is conservation of the wavenumber along the interface (ky). Defining the
  // incident angle from the measured ky, sin(theta1) = ky / k0, avoids a bias that the
  // finite beam width puts into the measured kx.
  const k0 = 2 * Math.PI / lam;
  const t1 = deg(Math.asin(k1.ky / k0)), t2 = WL.angleOf(k2);
  const snell = deg(Math.asin(Math.sin(rad(t1)) / N_GLASS));
  const yee = deg(Math.atan2(k1.ky, yeeKx(lam, N_GLASS, k1.ky)));
  refr.push({ lam, t1, t2, snell, yee, err: Math.abs(t2 - snell) / snell, errYee: Math.abs(t2 - yee) / yee });
  console.error(`  refraction at ${lam} cells/λ done in ${((Date.now() - t0) / 1000).toFixed(1)} s`);
}
const ordR = orders(refr.map(r => r.lam), refr.map(r => r.err));
refr.forEach((r, i) => log(`| ${r.lam} | ${r.t1.toFixed(3)}° | ${r.t2.toFixed(3)}° | ${r.snell.toFixed(3)}° | ${pct(r.err)} | ${r.yee.toFixed(3)}° | ${pct(r.errYee)} | ${ordR[i]} |`));
log();
log('The measured angle agrees with the Yee prediction to within 0.1% at every resolution, which checks the implementation. The difference from Snell\'s law comes from numerical dispersion: on a coarse grid the wave in glass travels slightly slower than c/n, so it bends a little more than Snell\'s law predicts. That difference falls roughly as 1/λ², the same second-order convergence as the wave speed. At the finest grid the measurement itself (finite beam, averaging region) starts to limit the observed order.');

// ---------------------------------------------------------------- 3. boundary
log();
log('## 3. Absorbing boundary');
log();
log('A short pulse is launched from the centre of a 100 × 100 cell region surrounded by a 20-cell absorbing layer. The field is recorded at two probes 5 cells inside the region: one facing the nearest edge (the wave hits the boundary head-on) and one in the corner (the wave hits both edges at 45°). The same pulse is also run in a much larger domain whose edges are too far away to matter within the recording time. Any difference between the two runs at a probe is the wave reflected by the boundary.');
log();

function pulseRun(boundary, pad) {
  const Wi = 100, P = 20, steps = 500;
  const sim = WL.createSolver({ W: Wi + 2 * pad, H: Wi + 2 * pad, P, boundary });
  sim.dirty = true;
  const src = sim.K(pad + 50, pad + 50);
  const probes = { side: sim.K(pad + 50, pad + 5), corner: sim.K(pad + 5, pad + 5) };
  const rec = { side: new Float64Array(steps), corner: new Float64Array(steps) };
  const tau = 6, t0 = 4 * tau;   // differentiated Gaussian: no DC, wavelengths around 20-40 cells
  let peakEnergy = 0, finalEnergy = 0;
  for (let t = 0; t < steps; t++) {
    sim.step();
    const x = (t - t0) / tau;
    sim.inject(src, -x * Math.exp(-x * x));
    rec.side[t] = sim.Ez[probes.side];
    rec.corner[t] = sim.Ez[probes.corner];
    if (pad === 0 && (t % 10 === 0 || t === steps - 1)) {
      let E = 0;
      for (let v = 0; v < Wi; v++) for (let u = 0; u < Wi; u++) {
        const k = sim.K(u, v);
        E += sim.Ez[k] ** 2 + sim.Hx[k] ** 2 + sim.Hy[k] ** 2;
      }
      peakEnergy = Math.max(peakEnergy, E);
      if (t === steps - 1) finalEnergy = E;
    }
  }
  return { rec, residual: finalEnergy / peakEnergy };
}

const ref = pulseRun('pml', 260);
const dB = x => (20 * Math.log10(x)).toFixed(1);
log('| boundary | reflection, side probe | reflection, corner probe | energy left after 500 steps |');
log('|---|---|---|---|');
const bResults = {};
for (const b of ['graded', 'pml']) {
  const r = pulseRun(b, 0);
  const res = {};
  for (const p of ['side', 'corner']) {
    let maxErr = 0, maxRef = 0;
    for (let t = 0; t < r.rec[p].length; t++) {
      maxErr = Math.max(maxErr, Math.abs(r.rec[p][t] - ref.rec[p][t]));
      maxRef = Math.max(maxRef, Math.abs(ref.rec[p][t]));
    }
    res[p] = maxErr / maxRef;
  }
  bResults[b] = { ...res, residual: r.residual };
  const name = b === 'pml' ? 'split-field PML' : 'graded loss (previous)';
  log(`| ${name} | ${dB(res.side)} dB (${pct(res.side)}) | ${dB(res.corner)} dB (${pct(res.corner)}) | ${r.residual.toExponential(2)} of peak |`);
}
log();
log('Reflection is the largest difference between the test run and the reference run at that probe, relative to the peak of the incoming pulse. Both layers use the same loss profile (cubic grading, 20 cells, maximum normalized loss 0.35), so the comparison isolates the difference in method: the graded layer damps every field component equally, while the PML damps each component only along its own direction. The app uses the PML by default; the boundary switch in the interface lets you compare them live.');

fs.writeFileSync(path.join(__dirname, '..', 'VALIDATION.md'), out.join('\n') + '\n');
console.error('\nWrote VALIDATION.md');
